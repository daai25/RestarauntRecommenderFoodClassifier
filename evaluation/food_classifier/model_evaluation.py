ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RESNET50_FOOD_CLASSIFIER_MODEL_PATH = os.path.join(ROOT, "src", "classify-pipeline", "food_classifier_RESNET50.pth")

def load_model() -> tuple[nn.Module, torch.device, transforms.Compose]:
    model, device, transformer = resnet_loader.load_resnet50_model(
        RESNET50_FOOD_CLASSIFIER_MODEL_PATH,
        out_features=78
    )

    return model, device, transformer

def load_data(transform: transforms.Compose, directory: str) -> DataLoader:
    dataset = ImageFolder(directory, transform=transform)
    return DataLoader(dataset, batch_size=128, num_workers=8, shuffle=False)

def evaluate_model(model: nn.Module, device: torch.device, dataloader: DataLoader) -> dict[str, float | Any]:
    all_predictions = []
    all_labels = []
    with torch.no_grad():
        for batch in tqdm(dataloader, desc="Evaluating model", unit="batch"):
            inputs, labels = batch
            inputs, labels = inputs.to(device), labels.to(device)
            outputs = model(inputs)
            _, predicted = torch.max(outputs, 1)
            all_predictions.extend(predicted.cpu().numpy())
            all_labels.extend(labels.cpu().numpy())

    # calculate the accuracy
    accuracy = sum([p == t for p, t in zip(all_predictions, all_labels)]) / len(all_labels)

    # calculate precision, recall, and F1-score
    precision, recall, f1, _ = precision_recall_fscore_support(
        all_labels, all_predictions, average="binary" if len(set(all_labels)) == 2 else "macro"
    )

    # calculate the confusion matrix
    cm = confusion_matrix(all_labels, all_predictions)

    return {
        "accuracy": accuracy,
        "precision": precision,
        "recall": recall,
        "f1_score": f1,
        "confusion_matrix": cm,
    }

def plot_results(result: dict[str, float | Any], title_acc: str, title_prec_rec_f1: str):
    """
    Plot the evaluation results of multiple models.

    1. Bar chart for accuracy.
    2. Grouped bar chart for precision, recall, and F1-score.
    """
    accuracies = result["accuracy"]
    precisions = result["precision"]
    recalls = result["recall"]
    f1_scores = result["f1_score"]

    x = np.arange(1)

    # --- Accuracy bar chart ---
    plt.figure(figsize=(10, 6))
    plt.bar(x, accuracies, color='skyblue')
    plt.xticks(x, " ", rotation=45, ha='right')
    plt.ylabel("Accuracy")
    plt.title(title_acc)
    plt.ylim(0.5, 1)
    plt.tight_layout()
    plt.grid(axis='y')
    plt.show()

    # --- Grouped bar chart for precision, recall, and F1 ---
    width = 0.25  # width of each bar

    plt.figure(figsize=(12, 6))
    plt.bar(x - width, precisions, width, label='Precision', color='mediumseagreen')
    plt.bar(x, recalls, width, label='Recall', color='cornflowerblue')
    plt.bar(x + width, f1_scores, width, label='F1-Score', color='salmon')

    plt.xticks(x, " ", rotation=45, ha='right')
    plt.ylabel("Score")
    plt.title(title_prec_rec_f1)
    plt.ylim(0.5, 1)
    plt.legend(loc='lower left')
    plt.tight_layout()
    plt.grid(axis='y')
    plt.show()

def plot_confusion_matrix(eval_results: dict, title: str):
    cm = eval_results["confusion_matrix"]

    # Plot only the heatmap without text labels
    fig, ax = plt.subplots(figsize=(8, 6))
    im = ax.imshow(cm, interpolation='nearest', cmap=plt.cm.Blues)
    ax.figure.colorbar(im, ax=ax)

    # Optional: Remove tick labels or set them to empty
    ax.set_xticks(np.arange(cm.shape[1]))
    ax.set_yticks(np.arange(cm.shape[0]))
    # add empty labels
    ax.set_xticklabels(["" for _ in range(cm.shape[1])])
    ax.set_yticklabels(["" for _ in range(cm.shape[0])])

    plt.xticks(rotation=45)
    ax.set_title(f"Confusion Matrix: {title}")
    ax.set_xlabel("Predicted label")
    ax.set_ylabel("True label")
    plt.tight_layout()
    plt.show()

